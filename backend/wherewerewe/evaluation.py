"""Spoiler eval: known shows, a cutoff, and later events that must never appear.

Each fixture holds hand-written summaries of the episodes up to the cutoff (in the
same JSON shape the summarizer produces) and regexes for well-known later events.
The recap is generated by the real assembly, generation and verification code; the
fixture fails if any forbidden pattern shows up in the final recap. It doubles as a
benchmark for comparing models and prompts (the draft leak count shows how much the
verifier is catching).
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path

from sqlalchemy import create_engine
from sqlalchemy.orm import Session
from sqlalchemy.pool import StaticPool

from .config import Settings
from .llm import prompts
from .llm.client import LLM, get_llm
from .llm.recap import build_context, write_recap
from .llm.verify import verify_recap
from .models import Base, Episode, EpisodeSummary, Show
from .services.library import parse_code

DEFAULT_FIXTURES = Path(__file__).resolve().parents[1] / "tests" / "spoiler_eval" / "fixtures"


@dataclass
class Forbidden:
    event: str
    pattern: re.Pattern[str]


@dataclass
class Fixture:
    name: str
    title: str
    cutoff: str
    episodes: list[dict]
    forbidden: list[Forbidden]


@dataclass
class EvalReport:
    fixture: str
    recap: str
    draft: str
    leaks: list[str] = field(default_factory=list)
    draft_leaks: list[str] = field(default_factory=list)
    removed_by_verifier: int = 0

    @property
    def passed(self) -> bool:
        return not self.leaks


def load_fixtures(directory: Path | None = None) -> list[Fixture]:
    directory = directory or Path(os.environ.get("EVAL_FIXTURES", DEFAULT_FIXTURES))
    if not directory.is_dir():
        raise FileNotFoundError(f"fixture directory not found: {directory}")
    fixtures = []
    for path in sorted(directory.glob("*.json")):
        data = json.loads(path.read_text())
        fixtures.append(
            Fixture(
                name=data["name"],
                title=data["title"],
                cutoff=data["cutoff"],
                episodes=data["episodes"],
                forbidden=[
                    Forbidden(f["event"], re.compile(f["pattern"], re.IGNORECASE))
                    for f in data["forbidden"]
                ],
            )
        )
    return fixtures


def find_leaks(text: str, forbidden: list[Forbidden]) -> list[str]:
    leaks = []
    for f in forbidden:
        match = f.pattern.search(text)
        if match:
            leaks.append(f"{f.event} (matched {match.group(0)!r})")
    return leaks


def fixture_session(fixture: Fixture, model: str) -> tuple[Session, Show, Episode]:
    """Load a fixture into a throwaway in-memory database."""
    engine = create_engine(
        "sqlite://", poolclass=StaticPool, connect_args={"check_same_thread": False}
    )
    Base.metadata.create_all(engine)
    session = Session(engine)
    show = Show(title=fixture.title)
    session.add(show)
    session.flush()
    for item in fixture.episodes:
        season, number = parse_code(item["code"])
        ep = Episode(show_id=show.id, season=season, episode=number, title=item.get("title"))
        session.add(ep)
        session.flush()
        session.add(
            EpisodeSummary(
                episode_id=ep.id,
                model=model,
                prompt_version=prompts.SUMMARY_VERSION,
                source_type="fixture",
                summary_json={"episode": item["code"], **item["summary"]},
            )
        )
    session.flush()
    cutoff_season, cutoff_ep = parse_code(fixture.cutoff)
    boundary = (
        session.query(Episode)
        .filter_by(show_id=show.id, season=cutoff_season, episode=cutoff_ep)
        .one()
    )
    return session, show, boundary


def run_fixture(
    fixture: Fixture,
    settings: Settings,
    *,
    length: str = "standard",
    llm: LLM | None = None,
    verify_llm: LLM | None = None,
) -> EvalReport:
    llm = llm or get_llm(settings)
    session, show, boundary = fixture_session(fixture, llm.model)
    try:
        ctx = build_context(session, show, boundary, length, settings, llm.context_tokens)
    finally:
        session.close()
    draft = write_recap(llm, ctx.text, length)
    final, removed = draft, 0
    if settings.recap_verify:
        result = verify_recap(verify_llm or get_llm(settings, verify=True), ctx.text, draft)
        final, removed = result.text, len(result.removed)
    return EvalReport(
        fixture=fixture.name,
        recap=final,
        draft=draft,
        leaks=find_leaks(final, fixture.forbidden),
        draft_leaks=find_leaks(draft, fixture.forbidden),
        removed_by_verifier=removed,
    )
